def detect_language() -> str:
    lang = (locale.getlocale()[0] or locale.getdefaultlocale()[0] or "en").lower()
    if lang.startswith("pl"):
        return "pl"
    if lang.startswith(("nb", "nn", "no")):
        return "no"
    return "en"


class Translator:
    def __init__(self, language: str | None = None):
        self.language = language if language in TRANSLATIONS else detect_language()

    def __call__(self, key: str, **kwargs) -> str:
        text = TRANSLATIONS.get(self.language, TRANSLATIONS["en"]).get(key, TRANSLATIONS["en"].get(key, key))
        return text.format(**kwargs) if kwargs else text
